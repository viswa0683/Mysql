--11)List all customers who purchased more than 1 units of any product, including the product name and total quantity purchased.

select  u.name,p.category,p.name product_name,sum(od.quantity)
from OrderDetails od,Products p,orders o,v_users u
where od.PRODUCT_ID=p.PRODUCT_ID
and od.order_id=o.order_id
and o.user_id=u.user_id
group by u.name,p.category,p.name
having sum(od.quantity)>0;

